import os
import graphviz
from PIL import Image, ImageDraw, ImageFont

def generate_and_frame_architecture():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    temp_base = os.path.join(base_dir, "temp_flowchart")
    final_output_path = os.path.join(base_dir, "final_presentation_diagram.png")

    # Step 1: Use Graphviz to generate a system architecture diagram
    dot = graphviz.Digraph(
        name="web_service_flow",
        comment="System Data Flow Architecture",
        format="png"
    )

    dot.attr(rankdir="LR", bgcolor="white")
    dot.attr("node", fontname="Helvetica", fontsize="11", style="filled")
    dot.attr("edge", fontname="Helvetica", fontsize="9", color="#475569")

    # Nodes
    dot.node("user", "User Device\n(Browser)", shape="ellipse", fillcolor="#e0e7ff", color="#4338ca")
    dot.node("cdn", "Cloudflare CDN\n(Edge Cache)", shape="hexagon", fillcolor="#fef3c7", color="#b45309")
    dot.node("lb", "Load Balancer\n(NGINX)", shape="diamond", fillcolor="#f1f5f9", color="#334155")
    dot.node("app", "App Cluster\n(FastAPI / Py)", shape="box", fillcolor="#dcfce7", color="#15803d")
    dot.node("cache", "Redis Cache\n(In-Memory)", shape="cylinder", fillcolor="#ffedd5", color="#c2410c")
    dot.node("db", "PostgreSQL\n(Primary DB)", shape="cylinder", fillcolor="#fee2e2", color="#b91c1c")

    # Edges
    dot.edge("user", "cdn", label="GET /")
    dot.edge("cdn", "lb", label="Cache Miss")
    dot.edge("lb", "app", label="Proxy")
    dot.edge("app", "cache", label="Check Session")
    dot.edge("app", "db", label="Read / Write")

    # Render diagram to temporary file
    temp_diagram_path = dot.render(temp_base, cleanup=True)

    # Step 2: Use Pillow to post-process the diagram into a presentation graphic
    with Image.open(temp_diagram_path) as diagram_img:
        diagram_img = diagram_img.convert("RGB")
        diag_w, diag_h = diagram_img.size

        # Canvas parameters
        header_height = 70
        footer_height = 40
        padding = 30
        border_thickness = 4

        canvas_w = diag_w + (padding * 2)
        canvas_h = diag_h + header_height + footer_height + (padding * 2)

        # Create main canvas
        canvas = Image.new("RGB", (canvas_w, canvas_h), color=(255, 255, 255))
        draw = ImageDraw.Draw(canvas)

        # Draw dark navy header banner
        header_color = (15, 23, 42)  # #0f172a
        draw.rectangle([(0, 0), (canvas_w, header_height)], fill=header_color)

        # Draw title text in header banner
        font = ImageFont.load_default()
        title_text = "SYSTEM ARCHITECTURE & DATA FLOW - PRODUCTION v1.0"
        draw.text((padding, 28), title_text, fill=(255, 255, 255), font=font)

        # Paste the Graphviz diagram in the center
        paste_x = padding
        paste_y = header_height + padding
        canvas.paste(diagram_img, (paste_x, paste_y))

        # Draw footer metadata bar
        footer_y = canvas_h - footer_height
        draw.rectangle([(0, footer_y), (canvas_w, canvas_h)], fill=(241, 245, 249))
        draw.text(
            (padding, footer_y + 14),
            "STATUS: VERIFIED & APPROVED | GENERATED BY GRAPHVIZ + PILLOW",
            fill=(71, 85, 105),
            font=font
        )

        # Draw outer decorative frame border
        for offset in range(border_thickness):
            draw.rectangle(
                [(offset, offset), (canvas_w - 1 - offset, canvas_h - 1 - offset)],
                outline=header_color
            )

        # Save the finalized presentation graphic
        canvas.save(final_output_path)
        print(f"Successfully combined Graphviz + Pillow -> {final_output_path}")
        print(f"Final output dimensions: {canvas_w}x{canvas_h}px")

    # Clean up temporary diagram image
    if os.path.exists(temp_diagram_path):
        os.remove(temp_diagram_path)

if __name__ == "__main__":
    generate_and_frame_architecture()
